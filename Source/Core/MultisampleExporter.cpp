juce::AudioBuffer<float> MultisampleExporter::renderZone (const Instrument& inst, const EngineSettings& settingsIn,
                                                          int key, int layer, int rr, Articulation art,
                                                          double sampleRate, float holdSeconds)
{
    auto s = settingsIn;
    s.width = 0.0f;
    s.velocityBlend = false;

    auto voice = std::make_unique<ResynthVoice>();
    voice->prepare (sampleRate);

    ResynthVoice::StartParams p;
    p.instrument = &inst;
    p.note = key;
    // a single-layer instrument plays at the source's own dynamic
    const float dyn = inst.settings.numLayers <= 1 ? s.sourceDynamic : inst.layerCentre (layer);
    p.velocity = dyn;
    p.forcedDynamic = dyn;
    p.roundRobin = rr;
    p.articulation = art;
    voice->start (p, s, 1.0f);

    const int block = 256;
    const int holdSamples = (int) (holdSeconds * sampleRate);
    const int maxSamples = (int) ((holdSeconds + 2.0 * s.releaseMs * 0.001 + 1.0) * sampleRate);
    const int capSamples = std::min (maxSamples, (int) (20.0 * sampleRate));

    juce::AudioBuffer<float> stereo (2, capSamples);
    stereo.clear();

    int pos = 0;
    bool releasedYet = false;
    while (pos < capSamples && voice->isActive())
    {
        const int n = std::min (block, capSamples - pos);
        if (! releasedYet && pos + n > holdSamples)
        {
            const int pre = holdSamples - pos;
            if (pre > 0)
                voice->render (stereo.getWritePointer (0, pos), stereo.getWritePointer (1, pos), pre, s, 1.0f, 0.0f);
            voice->release();
            releasedYet = true;
            if (pre > 0) { pos += pre; continue; }
        }
        voice->render (stereo.getWritePointer (0, pos), stereo.getWritePointer (1, pos), n, s, 1.0f, 0.0f);
        pos += n;
    }

    // trim the silent tail
    int len = pos;
    const auto* l = stereo.getReadPointer (0);
    while (len > 1 && std::abs (l[len - 1]) < 1.0e-5f)
        --len;
    len = std::max (len, std::min (pos, (int) (0.01 * sampleRate)));

    juce::AudioBuffer<float> mono (1, std::max (1, len));
    const float g = juce::Decibels::decibelsToGain (s.masterGainDb);
    for (int i = 0; i < len; ++i)
        mono.setSample (0, i, l[i] * g);
    return mono;
}

namespace
{
    juce::String u (const char* utf8) { return juce::String::fromUTF8 (utf8); }
    juce::String quoted (const juce::String& s) { return u ("“") + s + u ("”"); }
    juce::String noteName (int key) { return juce::MidiMessage::getMidiNoteName (key, true, true, 4); }

    juce::String safeName (juce::String s)
    {
        s = s.trim();
        auto r = s.retainCharacters ("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_ ").replaceCharacter (' ', '_');
        return r.isEmpty() ? juce::String ("Instrument") : r;
    }
}

ExportResult MultisampleExporter::exportSfz (const Instrument& inst, const EngineSettings& settings,
                                             const ExportOptions& opt, const Progress& progress)
{
    ExportResult result;
    const auto name = safeName (opt.instrumentName);
    auto root = opt.parentFolder.getChildFile (name);
    auto samples = root.getChildFile ("samples");
    if (! samples.createDirectory())
    {
        result.message = u ("Couldn’t create ") + quoted (samples.getFullPathName()) + ". Choose another folder.";
        return result;
    }

    std::vector<Articulation> arts;
    for (auto a : opt.articulations)
        if (a != Articulation::Legato)   // legato needs scripting; SFZ can't express it
            arts.push_back (a);
    if (arts.empty())
        arts.push_back (Articulation::Sustain);

    const auto& bs = inst.settings;
    const int total = inst.numKeys() * bs.numLayers * bs.numRoundRobins * (int) arts.size();
    int done = 0;

    juce::WavAudioFormat wav;
    juce::String sfz;
    sfz << "// " << opt.instrumentName << " - generated by Instant Virtual Instrument\n"
        << "// " << inst.numKeys() << " keys x " << bs.numLayers << " dynamic layers x "
        << bs.numRoundRobins << " round robins x " << (int) arts.size() << " articulation(s)\n\n"
        << "<control>\ndefault_path=samples/\n\n<global>\namp_veltrack=0\n\n";

    const bool multiArt = arts.size() > 1;
    for (size_t ai = 0; ai < arts.size(); ++ai)
    {
        const auto art = arts[ai];
        const auto artName = articulationName (art);
        sfz << "// ---- " << artName << "\n<master>\n";
        if (multiArt)
        {
            sfz << "sw_lokey=" << settings.keyswitchBase << " sw_hikey=" << (settings.keyswitchBase + kNumArticulations - 1)
                << " sw_last=" << (settings.keyswitchBase + (int) art);
            if (ai == 0)
                sfz << " sw_default=" << (settings.keyswitchBase + (int) art);
            sfz << "\n";
        }
        if (isOneShot (art) || art == Articulation::Pizzicato)
            sfz << "loop_mode=one_shot\n";
        else
            sfz << "ampeg_release=" << juce::String (settings.releaseMs * 0.001f, 3) << "\n";

        for (int layer = 0; layer < bs.numLayers; ++layer)
        {
            const int lovel = layer == 0 ? 1 : (int) std::ceil (layer * 127.0 / bs.numLayers);
            const int hivel = layer == bs.numLayers - 1 ? 127 : (int) std::ceil ((layer + 1) * 127.0 / bs.numLayers) - 1;

            for (int rr = 0; rr < bs.numRoundRobins; ++rr)
            {
                sfz << "<group> lovel=" << lovel << " hivel=" << hivel;
                if (bs.numRoundRobins > 1)
                    sfz << " seq_length=" << bs.numRoundRobins << " seq_position=" << (rr + 1);
                sfz << "\n";

                for (int key = bs.lowKey; key <= bs.highKey; ++key)
                {
                    if (progress && ! progress ((float) done / (float) total))
                    {
                        result.message = u ("Export stopped. The ") + juce::String (result.filesWritten) + " samples written so far are in " + quoted (root.getFullPathName()) + ".";
                        return result;
                    }

                    auto audio = renderZone (inst, settings, key, layer, rr, art, opt.sampleRate, opt.holdSeconds);
                    if (audio.getMagnitude (0, 0, audio.getNumSamples()) > 1.0f)
                        ++result.clippedFiles;

                    const auto fileName = name + "_" + artName + "_" + juce::String (key).paddedLeft ('0', 3) + "_"
                                        + noteName (key).replace ("#", "s") + "_L" + juce::String (layer + 1)
                                        + "_RR" + juce::String (rr + 1) + ".wav";
                    auto file = samples.getChildFile (fileName);
                    file.deleteFile();

                    std::unique_ptr<juce::OutputStream> stream = file.createOutputStream();
                    if (stream == nullptr)
                    {
                        result.message = u ("Couldn’t write ") + quoted (file.getFullPathName()) + ". Check the disk has room, or choose another folder.";
                        return result;
                    }
                    auto writer = wav.createWriterFor (stream, juce::AudioFormatWriterOptions{}
                                                                  .withSampleRate (opt.sampleRate)
                                                                  .withNumChannels (1)
                                                                  .withBitsPerSample (opt.bitDepth));
                    if (writer == nullptr)
                    {
                        result.message = u ("Couldn’t write WAV files at this sample rate. Export again from a project at 44.1 or 48 kHz.");
                        return result;
                    }
                    writer->writeFromAudioSampleBuffer (audio, 0, audio.getNumSamples());
                    writer.reset();

                    sfz << "<region> sample=" << fileName << " key=" << key << " pitch_keycenter=" << key << "\n";
                    ++result.filesWritten;
                    ++done;
                }
            }
        }
        sfz << "\n";
    }

    result.sfzFile = root.getChildFile (name + ".sfz");
    if (! result.sfzFile.replaceWithText (sfz))
    {
        result.message = u ("Couldn’t write ") + quoted (result.sfzFile.getFullPathName()) + ". Check the disk has room, or choose another folder.";
        return result;
    }

    result.ok = true;
    result.message = "Exported " + juce::String (result.filesWritten) + " samples and " + quoted (result.sfzFile.getFileName())
                   + " to " + quoted (root.getFullPathName()) + ". Open the .sfz in any SFZ player.";
    if (result.clippedFiles > 0)
        result.message << " " << result.clippedFiles << u (" of them clip — lower Gain and export again.");
    if (progress)
        progress (1.0f);
    return result;
}

